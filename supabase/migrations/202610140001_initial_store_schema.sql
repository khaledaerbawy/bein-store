-- Bein Store schema reference.
-- No products, prices, stock, customers, or orders are seeded.
-- This is a portable reference for the schema already applied to the connected project.

create extension if not exists pgcrypto;

create table if not exists public.categories (
  id uuid primary key default gen_random_uuid(),
  name_ar text not null,
  name_en text not null,
  slug text not null unique,
  description_ar text,
  description_en text,
  image_url text,
  is_active boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  category_id uuid references public.categories(id) on delete set null,
  sku text unique,
  slug text not null unique,
  name_ar text not null,
  name_en text not null,
  brand text,
  model text,
  description_ar text,
  description_en text,
  specifications jsonb not null default '{}'::jsonb,
  price_egp numeric(12,2) check (price_egp is null or price_egp >= 0),
  compare_at_price_egp numeric(12,2) check (compare_at_price_egp is null or compare_at_price_egp >= 0),
  image_urls text[] not null default '{}',
  is_active boolean not null default false,
  is_featured boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.inventory (
  product_id uuid primary key references public.products(id) on delete cascade,
  quantity_on_hand integer not null default 0 check (quantity_on_hand >= 0),
  low_stock_threshold integer not null default 2 check (low_stock_threshold >= 0),
  updated_at timestamptz not null default now()
);

create table if not exists public.inventory_movements (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.products(id) on delete restrict,
  quantity_delta integer not null check (quantity_delta <> 0),
  reason text not null,
  reference text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  phone text,
  preferred_language text not null default 'ar' check (preferred_language in ('ar','en')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.admin_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'admin' check (role in ('admin','manager')),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_name text not null,
  customer_phone text not null,
  customer_email text,
  shipping_address text,
  city text,
  notes text,
  language text not null default 'ar' check (language in ('ar','en')),
  status text not null default 'new' check (status in ('new','confirmed','preparing','shipped','completed','cancelled')),
  currency text not null default 'EGP' check (currency = 'EGP'),
  subtotal_egp numeric(12,2) not null default 0 check (subtotal_egp >= 0),
  shipping_fee_egp numeric(12,2) not null default 0 check (shipping_fee_egp >= 0),
  total_egp numeric(12,2) not null default 0 check (total_egp >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name_snapshot text not null,
  sku_snapshot text,
  quantity integer not null check (quantity > 0),
  unit_price_egp numeric(12,2) not null check (unit_price_egp >= 0),
  line_total_egp numeric(12,2) not null check (line_total_egp >= 0),
  created_at timestamptz not null default now()
);

create index if not exists products_category_id_idx on public.products(category_id);
create index if not exists products_active_idx on public.products(is_active);
create index if not exists orders_status_created_at_idx on public.orders(status, created_at desc);
create index if not exists order_items_order_id_idx on public.order_items(order_id);
create index if not exists inventory_movements_product_created_at_idx on public.inventory_movements(product_id, created_at desc);
create index if not exists inventory_movements_created_by_idx on public.inventory_movements(created_by);
create index if not exists order_items_product_id_idx on public.order_items(product_id);

alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.inventory enable row level security;
alter table public.inventory_movements enable row level security;
alter table public.profiles enable row level security;
alter table public.admin_roles enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

grant select on public.categories, public.products to anon, authenticated;
grant select on public.inventory, public.inventory_movements, public.admin_roles, public.orders, public.order_items to authenticated;
grant select, insert, update on public.profiles to authenticated;

-- Categories: public sees only active rows; admins can see/manage all rows.
drop policy if exists "Read active categories or admin access" on public.categories;
create policy "Read active categories or admin access" on public.categories for select to anon, authenticated
using (is_active = true or exists (select 1 from public.admin_roles ar where ar.user_id = (select auth.uid()) and ar.is_active = true));
drop policy if exists "Admins insert categories" on public.categories;
create policy "Admins insert categories" on public.categories for insert to authenticated
with check (exists (select 1 from public.admin_roles ar where ar.user_id = (select auth.uid()) and ar.is_active = true));
drop policy if exists "Admins update categories" on public.categories;
create policy "Admins update categories" on public.categories for update to authenticated
using (exists (select 1 from public.admin_roles ar where ar.user_id = (select auth.uid()) and ar.is_active = true))
with check (exists (select 1 from public.admin_roles ar where ar.user_id = (select auth.uid()) and ar.is_active = true));
drop policy if exists "Admins delete categories" on public.categories;
create policy "Admins delete categories" on public.categories for delete to authenticated
using (exists (select 1 from public.admin_roles ar where ar.user_id = (select auth.uid()) and ar.is_active = true));

