-- User profiles are limited to the signed-in user's own row.
drop policy if exists "Users read own profile" on public.profiles;
create policy "Users read own profile" on public.profiles for select to authenticated
using (id = (select auth.uid()));
drop policy if exists "Users insert own profile" on public.profiles;
create policy "Users insert own profile" on public.profiles for insert to authenticated
with check (id = (select auth.uid()));
drop policy if exists "Users update own profile" on public.profiles;
create policy "Users update own profile" on public.profiles for update to authenticated
using (id = (select auth.uid())) with check (id = (select auth.uid()));

-- Admin users can read their own role record; only trusted project owners should provision admin_roles.
drop policy if exists "Users can read own admin role" on public.admin_roles;
create policy "Users can read own admin role" on public.admin_roles for select to authenticated
using (user_id = (select auth.uid()));

