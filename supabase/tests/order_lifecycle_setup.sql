-- Minimal Supabase-like schema for free, disposable PostgreSQL lifecycle tests.
-- This schema is isolated to a GitHub Actions service container and is never production data.

CREATE ROLE anon;
CREATE ROLE authenticated;

CREATE SCHEMA auth;
CREATE OR REPLACE FUNCTION auth.uid()
RETURNS uuid
LANGUAGE sql
STABLE
AS $function$
  SELECT NULLIF(current_setting('request.jwt.claim.sub', true), '')::uuid;
$function$;

CREATE TABLE public.products (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name_ar text NOT NULL,
  sku text,
  price_egp numeric(12,2),
  is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE public.inventory (
  product_id uuid PRIMARY KEY REFERENCES public.products(id) ON DELETE CASCADE,
  quantity_on_hand integer NOT NULL CHECK (quantity_on_hand >= 0),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.orders (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  order_number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  customer_name text NOT NULL,
  customer_phone text NOT NULL,
  customer_email text,
  shipping_address text,
  city text,
  notes text,
  language text NOT NULL DEFAULT 'ar',
  status text NOT NULL DEFAULT 'new',
  currency text NOT NULL DEFAULT 'EGP',
  subtotal_egp numeric(12,2) NOT NULL DEFAULT 0,
  shipping_fee_egp numeric(12,2) NOT NULL DEFAULT 0,
  total_egp numeric(12,2) NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.order_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id uuid NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  product_id uuid REFERENCES public.products(id) ON DELETE SET NULL,
  product_name_snapshot text NOT NULL,
  sku_snapshot text,
  quantity integer NOT NULL CHECK (quantity > 0),
  unit_price_egp numeric(12,2) NOT NULL CHECK (unit_price_egp >= 0),
  line_total_egp numeric(12,2) NOT NULL CHECK (line_total_egp >= 0),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.inventory_movements (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  product_id uuid NOT NULL REFERENCES public.products(id) ON DELETE RESTRICT,
  quantity_delta integer NOT NULL CHECK (quantity_delta <> 0),
  reason text NOT NULL,
  reference text,
  created_by uuid,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.admin_roles (
  user_id uuid PRIMARY KEY,
  is_active boolean NOT NULL DEFAULT true
);

-- The cancellation/return routine mirrors the production function in
-- 202610160001_order_security_hardening.sql. It restores stock only once.
CREATE OR REPLACE FUNCTION public.restore_order_inventory(p_order_id uuid, p_reason text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_order_number bigint;
  v_item record;
  v_return_reference text;
BEGIN
  SELECT order_number INTO v_order_number
  FROM public.orders WHERE id = p_order_id;
  IF NOT FOUND THEN RETURN; END IF;
  v_return_reference := 'Return for Order #' || v_order_number;

  FOR v_item IN
    SELECT oi.product_id, SUM(oi.quantity)::integer AS quantity
    FROM public.order_items oi
    WHERE oi.order_id = p_order_id AND oi.product_id IS NOT NULL
    GROUP BY oi.product_id
  LOOP
    IF EXISTS (
      SELECT 1 FROM public.inventory_movements im
      WHERE im.product_id = v_item.product_id
        AND im.reference = 'Order #' || v_order_number
        AND im.reason = 'بيع عبر المتجر'
        AND im.quantity_delta < 0
    ) AND NOT EXISTS (
      SELECT 1 FROM public.inventory_movements im
      WHERE im.product_id = v_item.product_id
        AND im.reference = v_return_reference
        AND im.reason = p_reason
        AND im.quantity_delta > 0
    ) THEN
      UPDATE public.inventory
      SET quantity_on_hand = quantity_on_hand + v_item.quantity,
          updated_at = clock_timestamp()
      WHERE product_id = v_item.product_id;
      IF FOUND THEN
        INSERT INTO public.inventory_movements(product_id, quantity_delta, reason, reference, created_by)
        VALUES (v_item.product_id, v_item.quantity, p_reason, v_return_reference, NULL);
      END IF;
    END IF;
  END LOOP;
END;
$function$;

CREATE OR REPLACE FUNCTION public.admin_update_order_status(p_order_id uuid, p_new_status text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_current_status text;
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM public.admin_roles ar
    WHERE ar.user_id = (SELECT auth.uid()) AND ar.is_active = true
  ) THEN
    RAISE EXCEPTION 'ADMIN_ACCESS_REQUIRED' USING ERRCODE = '42501';
  END IF;
  IF p_new_status NOT IN ('new', 'confirmed', 'preparing', 'shipped', 'completed', 'cancelled') THEN
    RAISE EXCEPTION 'INVALID_ORDER_STATUS' USING ERRCODE = '22023';
  END IF;
  SELECT status INTO v_current_status
  FROM public.orders WHERE id = p_order_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'ORDER_NOT_FOUND' USING ERRCODE = 'P0002'; END IF;
  IF v_current_status = 'cancelled' AND p_new_status <> 'cancelled' THEN
    RAISE EXCEPTION 'ORDER_ALREADY_CANCELLED';
  END IF;
  IF p_new_status = 'cancelled' AND v_current_status IN ('shipped', 'completed') THEN
    RAISE EXCEPTION 'ORDER_CANNOT_CANCEL_AFTER_SHIPMENT';
  END IF;

  UPDATE public.orders SET status = p_new_status, updated_at = clock_timestamp()
  WHERE id = p_order_id;

  IF p_new_status = 'cancelled' AND v_current_status <> 'cancelled' THEN
    PERFORM public.restore_order_inventory(p_order_id, 'إرجاع مخزون بعد إلغاء الطلب');
  END IF;
END;
$function$;

GRANT EXECUTE ON FUNCTION public.admin_update_order_status(uuid, text) TO authenticated;
